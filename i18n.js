export function presentReason(reason, language = DEFAULT_LANGUAGE, quoteComparabilityAssessed = true) {
  const raw = String(reason || "");
  if (language === "zh-TW") {
    if (raw.includes("Weak/irrelevant Category Fit")) return t("reason.category", language);
    if (raw.includes("Material contradiction")) return `${t("reason.contradiction", language)} ${raw.match(/\(([^)]+)\)/)?.[1] || ""}`.trim();
    if (raw.includes("Commercial terms are incomplete")) return t("reason.terms", language);
    if (raw.includes("Quote bases are not comparable")) return quoteComparabilityAssessed ? t("reason.quotes", language) : t("reason.quotesUnknown", language);
    if (raw.includes("Payment exposure is UNKNOWN")) return t("reason.payment", language);
    if (raw.includes("Evidence Quality is LOW or UNKNOWN")) return t("reason.evidenceLow", language);
    if (raw.includes("Evidence Quality is not strong")) return t("reason.evidenceNotStrong", language);
    if (raw.includes("Blocking UNKNOWN")) return t("reason.blockingUnknown", language);
    if (raw.includes("Positive evidence supports pursuit")) return t("reason.positive", language);
    if (raw.includes("KYC GATE: sanctions")) return t("reason.kycVeto", language);
    if (raw.includes("KYC GATE: beneficial-owner")) return t("reason.kycIncomplete", language);
    if (raw.includes("MARGIN GATE: gross margin")) return t("reason.marginBelow", language);
    if (raw.includes("MARGIN GATE: compliance")) return t("reason.marginShift", language);
    if (raw.includes("Invalid dimension value")) return t("reason.invalid", language);
  }
  return raw
    .replace(/^Rule \d+:\s*/, "")
    .replace(/^Rule:\s*/, "")
    .replace(/\bPURSUE_NOW\b/g, t("state.pursueNow", language))
    .replace(/\bPURSUE_CONDITIONALLY\b/g, t("state.pursueConditionally", language))
    .replace(/\bHOLD_FOR_EVIDENCE\b/g, t("state.holdForEvidence", language))
    .replace(/\bDO_NOT_PURSUE\b/g, t("state.doNotPursue", language))
    .replace(/\bESCALATE\b/g, t("state.escalate", language));
}

